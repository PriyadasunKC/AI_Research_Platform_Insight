_ALIAS_TO_CANONICAL: dict[str, str] = {}
for _canonical, _aliases in CANONICAL_ALIASES.items():
    for _alias in _aliases:
        _ALIAS_TO_CANONICAL[_alias] = _canonical


def get_aliases_for(canonical_name: str) -> list[str]:
    """Return all known alternative names for the given canonical name.

    Returns an empty list if the name has no registered aliases.
    """
    return list(CANONICAL_ALIASES.get(canonical_name, []))


def resolve_to_canonical(name: str) -> str:
    """Return the canonical name for a given alias, or name unchanged if not found.

    Searches both:
      1. Direct canonical-name keys (already canonical → returned as-is)
      2. Alias lists (alias → canonical lookup)
    """
    name = name.strip()
    if not name:
        return name
    if name in CANONICAL_ALIASES:
        return name
    return _ALIAS_TO_CANONICAL.get(name, name)