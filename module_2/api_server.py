"""
api_server.py — External REST API for the Essay Accuracy Checker (Stage 2)

Exposes the essay-accuracy pipeline over HTTP so other modules in this
project (e.g. Module 3) can submit a Sinhala essay — as JSON text or as an
uploaded .txt file — and get back the same score, claim-by-claim verdicts,
and teacher-style corrective feedback the Streamlit UI shows — without
importing this project's Python code.

Run with:
    venv/Scripts/uvicorn api_server:app --host 0.0.0.0 --port 8010

Interactive API docs (auto-generated by FastAPI) are then available at
http://localhost:8010/docs

Auth: every request must include a valid X-API-Key header. Keys and their
associated caller names are configured via ESSAY_API_KEYS in .env — see
.env.example. This identifies *which module* called (stored as `caller`
on every saved run); callers may additionally pass `submitted_by` in the
request body for their own tracing (e.g. a student/essay ID).
"""

from __future__ import annotations

import json
import os
import time
from typing import Optional

from dotenv import load_dotenv
from fastapi import FastAPI, File, Form, Header, HTTPException, Request, UploadFile
from fastapi.middleware.cors import CORSMiddleware
from pydantic import BaseModel, Field, ValidationError

load_dotenv()

import essay_accuracy_checker as eac
import mongo_store

ANTHROPIC_API_KEY: str = os.environ.get("ANTHROPIC_API_KEY", "")


# API key configuration — "key1:CallerName,key2:OtherCaller" from .env

def _load_api_keys() -> dict[str, str]:
    raw = os.environ.get("ESSAY_API_KEYS", "")
    keys: dict[str, str] = {}
    for pair in raw.split(","):
        pair = pair.strip()
        if not pair or ":" not in pair:
            continue
        key, _, name = pair.partition(":")
        key = key.strip()
        name = name.strip() or "unknown"
        if key:
            keys[key] = name
    return keys


_API_KEYS: dict[str, str] = _load_api_keys()


def _authenticate(x_api_key: Optional[str]) -> str:
    """Validate the X-API-Key header and return the caller's display name."""
    if not _API_KEYS:
        raise HTTPException(
            status_code=503,
            detail="No API keys configured on the server — set ESSAY_API_KEYS in .env.",
        )
    if not x_api_key or x_api_key not in _API_KEYS:
        raise HTTPException(status_code=401, detail="Missing or invalid X-API-Key header.")
    return _API_KEYS[x_api_key]


# App

app = FastAPI(
    title="Sinhala Historical Essay Accuracy API",
    description=(
        "Submit a raw Sinhala historical essay and receive a Knowledge-Graph-"
        "grounded accuracy score, claim-by-claim verdicts, and teacher-style "
        "corrective feedback for any factual errors."
    ),
    version="1.0.0",
)

# Internal, trusted multi-module project — permissive CORS. Tighten
